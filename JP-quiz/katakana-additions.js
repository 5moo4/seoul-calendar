function normalizeKatakanaReading(kana, reading) {
  const expected = ['아','애','아','애','어','에','어','에','오','아','애','이','오','우','어','에','이','우','우','이','이'];
  const expectedMedial = { 아: 0, 애: 1, 어: 4, 에: 5, 오: 8, 우: 13, 으: 18, 이: 20 };
  const finalSound = ['', 'ㄱ','ㄲ','ㄳ','ㄴ','ㄵ','ㄶ','ㄷ','ㄹ','ㄺ','ㄻ','ㄼ','ㄽ','ㄾ','ㄿ','ㅀ','ㅁ','ㅂ','ㅄ','ㅅ','ㅆ','ㅇ','ㅈ','ㅊ','ㅋ','ㅌ','ㅍ','ㅎ'];
  let remaining = (kana.match(/ー/g) || []).length;
  const chars = [...reading];
  for (let i = 1; i < chars.length && remaining > 0; i++) {
    const code = chars[i - 1].codePointAt(0) - 0xac00;
    if (code >= 0 && code <= 11171 && chars[i] === expected[Math.floor(code / 28) % 21]) {
      chars[i] = 'ㅡ';
      remaining--;
      continue;
    }
    const nextCode = chars[i].codePointAt(0) - 0xac00;
    if (code >= 0 && code <= 11171 && nextCode >= 0 && nextCode <= 11171) {
      const onset = Math.floor(nextCode / 588);
      const medial = Math.floor(nextCode / 28) % 21;
      const vowel = expected[Math.floor(code / 28) % 21];
      if (onset === 11 && medial === expectedMedial[vowel]) {
        chars[i] = 'ㅡ' + finalSound[nextCode % 28];
        remaining--;
      }
    }
  }
  return chars.join('');
}

